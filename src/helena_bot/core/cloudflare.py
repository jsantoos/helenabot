"""
Module: helena_bot.core.cloudflare

Handles the extraction of the public URL from a running Cloudflare tunnel.

This module is responsible for reading the URL generated by a `cloudflared`
container or background process. The tunnel URL is expected to be written to a
shared file on disk (e.g., by a sidecar container in Docker).

The function `read_tunnel_url` is used during system startup to obtain
the externally accessible endpoint needed to register webhooks for the
Telegram bot.

Typical use:
    url = read_tunnel_url(timeout=60)

Notes:
- This module assumes the file is written by another process before timeout.
- Logging is used to trace the success or failure of tunnel acquisition.

Applies:
- PEP 8: Code style
- PEP 20: Zen of Python
- PEP 257: Docstring conventions
- PEP 484: Type hints
"""

import logging
import os
import time

logger = logging.getLogger(__name__)


def read_tunnel_url(
    timeout: int = 60, shared_file: str = "/shared-data/tunnel_url.txt"
) -> str:
    """
    Attempts to read the public Cloudflare tunnel URL from a shared file.

    This function continuously checks for the presence of a file that contains the
    Cloudflare tunnel URL. It is designed to be used during the initialization
    of the system to retrieve the external address for webhook registration.

    Args:
        timeout (int): Maximum time in seconds to wait for the file and URL content.
                       Defaults to 60 seconds.
        shared_file (str): Full path to the file where the tunnel URL is expected.
                           Defaults to "/shared-data/tunnel_url.txt".

    Returns:
        str: The extracted public URL as a string if found within the timeout period;
             an empty string otherwise.

    Logging:
        - Logs info when the URL is successfully read.
        - Logs a warning if the URL cannot be retrieved within the timeout.
    """
    waited = 0
    while waited < timeout:
        if os.path.exists(shared_file):
            with open(shared_file, "r", encoding="utf-8") as file:
                url = file.read().strip()
                if url:
                    logger.info("URL do túnel Cloudflare lida com sucesso: %s", url)
                    return url
        time.sleep(2)
        waited += 2

    logger.warning(
        "Timeout ao tentar ler a URL do túnel Cloudflare após %d segundos.", timeout
    )
    return ""
